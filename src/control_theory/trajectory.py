"""
Trajectory Generation Framework

This module provides unified trajectory generation capabilities for control systems.
It abstracts the rollout logic that was previously duplicated across different controllers.

Key Components:
    - Trajectory: Data structure for storing trajectory information
    - TrajectoryGenerator: Unified trajectory generation using JAX scan
    - BatchTrajectoryGenerator: Efficient batch trajectory generation
    - TrajectoryAnalyzer: Analysis and visualization tools

Mathematical Foundation:
    A trajectory is a sequence: {(x_t, u_t, r_t)}_{t=0}^T
    Generated by: x_{t+1} = f(x_t, u_t, w_t), u_t = π(x_t, t)
"""

from typing import NamedTuple, Dict, Any, Optional, Callable, List
import jax
import jax.numpy as jnp
from jax import random

from .core import State, Action, Reward, Info, ControlPolicy, create_state, create_action
from .environments import ControlEnvironment


class Trajectory(NamedTuple):
    """
    Data structure for storing trajectory information.
    
    Contains all information from a single trajectory execution:
    - States, actions, rewards over time
    - Metadata and diagnostic information
    - Performance metrics
    """
    states: jnp.ndarray      # Shape: (T+1, state_dim)
    actions: jnp.ndarray     # Shape: (T, action_dim)
    rewards: jnp.ndarray     # Shape: (T,)
    times: jnp.ndarray       # Shape: (T+1,)
    
    # Optional components
    infos: Optional[Dict[str, jnp.ndarray]] = None
    metadata: Optional[Dict[str, Any]] = None
    
    @property
    def length(self) -> int:
        """Length of trajectory (number of time steps)."""
        return self.actions.shape[0]
    
    @property
    def total_reward(self) -> float:
        """Total cumulative reward."""
        return float(jnp.sum(self.rewards))
    
    def get_state_at_time(self, t: int) -> jnp.ndarray:
        """Get state at specific time index."""
        return self.states[t]
    
    def get_action_at_time(self, t: int) -> jnp.ndarray:
        """Get action at specific time index."""
        return self.actions[t]


class BatchTrajectories(NamedTuple):
    """
    Data structure for storing batch of trajectories.
    
    Efficiently stores multiple trajectories with shared structure:
    - Batch dimension first: (batch_size, time_steps, feature_dim)
    - Enables efficient parallel processing and analysis
    """
    states: jnp.ndarray      # Shape: (batch_size, T+1, state_dim)
    actions: jnp.ndarray     # Shape: (batch_size, T, action_dim)
    rewards: jnp.ndarray     # Shape: (batch_size, T)
    times: jnp.ndarray       # Shape: (T+1,) - shared across batch
    
    # Optional batch components
    infos: Optional[Dict[str, jnp.ndarray]] = None
    metadata: Optional[Dict[str, Any]] = None
    
    @property
    def batch_size(self) -> int:
        """Number of trajectories in batch."""
        return self.states.shape[0]
    
    @property
    def length(self) -> int:
        """Length of trajectories (number of time steps)."""
        return self.actions.shape[1]
    
    @property
    def total_rewards(self) -> jnp.ndarray:
        """Total rewards for each trajectory in batch."""
        return jnp.sum(self.rewards, axis=1)
    
    def get_trajectory(self, idx: int) -> Trajectory:
        """Extract single trajectory from batch."""
        trajectory_infos = None
        if self.infos:
            trajectory_infos = {k: v[idx] for k, v in self.infos.items()}
            
        return Trajectory(
            states=self.states[idx],
            actions=self.actions[idx],
            rewards=self.rewards[idx],
            times=self.times,
            infos=trajectory_infos,
            metadata=self.metadata
        )


class TrajectoryGenerator:
    """
    Unified trajectory generation using JAX scan for efficiency.
    
    This class abstracts the rollout logic that was previously duplicated
    across different controllers. It provides:
    - Efficient JAX-compiled trajectory generation
    - Support for both deterministic and stochastic policies
    - Batch trajectory generation
    - Flexible stopping conditions
    """
    
    def __init__(self, 
                 policy: ControlPolicy, 
                 environment: ControlEnvironment,
                 compile_trajectory_gen: bool = True):
        """
        Initialize trajectory generator.
        
        Args:
            policy: Control policy to use
            environment: Environment to execute in  
            compile_trajectory_gen: Whether to JIT compile trajectory generation
        """
        self.policy = policy
        self.environment = environment
        
        # JIT compile trajectory generation for efficiency
        if compile_trajectory_gen:
            self._generate_trajectory_compiled = jax.jit(
                self._generate_trajectory_impl,
                static_argnames=['n_steps']
            )
        else:
            self._generate_trajectory_compiled = self._generate_trajectory_impl
    
    def generate_trajectory(self, 
                          initial_state: State,
                          n_steps: int,
                          key: random.PRNGKey) -> Trajectory:
        """
        Generate single trajectory.
        
        Args:
            initial_state: Starting state
            n_steps: Number of time steps
            key: Random key for stochastic elements
            
        Returns:
            Complete trajectory
        """
        return self._generate_trajectory_compiled(initial_state, n_steps, key)
    
    def _generate_trajectory_impl(self, 
                                initial_state: State,
                                n_steps: int, 
                                key: random.PRNGKey) -> Trajectory:
        """Internal implementation of trajectory generation."""
        
        def step_fn(carry, time_step):
            """Single step function for JAX scan."""
            key, state = carry
            key, policy_key, env_key = random.split(key, 3)
            
            # Compute action using policy
            current_time = time_step * self.environment.config.dt
            action = self.policy.compute_action(
                state, 
                time=current_time,
                key=policy_key if self.policy.is_stochastic else None
            )
            
            # Take environment step
            next_state, reward, done, info = self.environment.step(env_key, state, action)
            
            # Store step information
            step_data = {
                'state': state.data,
                'action': action.data, 
                'reward': reward.value,
                'next_state': next_state.data,
                'done': done,
                'info': info.data if info else {}
            }
            
            return (key, next_state), step_data
        
        # Execute trajectory using scan
        time_steps = jnp.arange(n_steps)
        (_, final_state), trajectory_data = jax.lax.scan(
            step_fn, (key, initial_state), time_steps
        )
        
        # Extract trajectory components
        states = jnp.concatenate([
            jnp.expand_dims(initial_state.data, 0),
            trajectory_data['next_state']
        ], axis=0)
        
        actions = trajectory_data['action']
        rewards = trajectory_data['reward']
        times = jnp.arange(n_steps + 1) * self.environment.config.dt
        
        # Extract info data
        infos = {}
        if trajectory_data['info']:
            # Collect info from all time steps
            for key in trajectory_data['info']:
                if isinstance(trajectory_data['info'][key], dict):
                    for subkey in trajectory_data['info'][key]:
                        infos[f"{key}_{subkey}"] = trajectory_data['info'][key][subkey]
                else:
                    infos[key] = trajectory_data['info'][key]
        
        return Trajectory(
            states=states,
            actions=actions,
            rewards=rewards,
            times=times,
            infos=infos if infos else None,
            metadata={'policy': self.policy.__class__.__name__}
        )
    
    def generate_batch_trajectories(self,
                                  batch_size: int,
                                  n_steps: int,
                                  key: random.PRNGKey) -> BatchTrajectories:
        """
        Generate batch of trajectories efficiently.
        
        Args:
            batch_size: Number of trajectories to generate
            n_steps: Number of time steps per trajectory  
            key: Random key
            
        Returns:
            Batch of trajectories
        """
        # Split keys for parallel trajectory generation
        keys = random.split(key, batch_size + 1)
        reset_key, trajectory_keys = keys[0], keys[1:]
        
        # Reset environment for batch
        initial_states = self.environment.reset(reset_key, batch_size)
        
        # Generate trajectories in parallel using vmap
        batch_generate_fn = jax.vmap(
            self._generate_trajectory_compiled,
            in_axes=(0, None, 0)
        )
        
        # Convert single state to batch format if needed
        if batch_size == 1:
            # Special handling for single trajectory case
            single_trajectory = self._generate_trajectory_compiled(initial_states, n_steps, trajectory_keys[0])
            
            # Convert to batch format
            batch_trajectories = Trajectory(
                states=jnp.expand_dims(single_trajectory.states, 0),
                actions=jnp.expand_dims(single_trajectory.actions, 0), 
                rewards=jnp.expand_dims(single_trajectory.rewards, 0),
                times=single_trajectory.times,  # Times are same for all trajectories
                infos={k: jnp.expand_dims(v, 0) for k, v in single_trajectory.infos.items()} if single_trajectory.infos else None,
                metadata=single_trajectory.metadata
            )
        else:
            # Handle batch case properly
            if initial_states.data.ndim == 1:
                # Single state returned, need to tile for batch
                batch_initial_data = jnp.tile(initial_states.data, (batch_size, 1))
                batch_metadata = {}
                if initial_states.metadata:
                    for k, v in initial_states.metadata.items():
                        if jnp.isscalar(v) or v.ndim == 0:
                            batch_metadata[k] = jnp.tile(v, (batch_size,))
                        else:
                            batch_metadata[k] = jnp.tile(v, (batch_size, 1)) if v.ndim == 1 else v
                            
                batch_initial_states = create_state(
                    data=batch_initial_data,
                    time=initial_states.time,
                    **batch_metadata
                )
            else:
                # Already in batch format
                batch_initial_states = initial_states
            
            # Generate batch trajectories using vmap
            batch_trajectories = batch_generate_fn(
                batch_initial_states, n_steps, trajectory_keys
            )
        
        # Convert to BatchTrajectories format
        return BatchTrajectories(
            states=batch_trajectories.states,
            actions=batch_trajectories.actions,
            rewards=batch_trajectories.rewards,
            times=batch_trajectories.times[0],  # Times are same for all trajectories
            infos=batch_trajectories.infos,
            metadata={
                'batch_size': batch_size,
                'policy': self.policy.__class__.__name__,
                'environment': self.environment.__class__.__name__
            }
        )


class TrajectoryAnalyzer:
    """
    Analysis and visualization tools for trajectories.
    
    Provides:
    - Performance metric computation
    - Statistical analysis
    - Trajectory visualization
    - Comparison between different policies/environments
    """
    
    @staticmethod
    def compute_performance_metrics(trajectory: Trajectory) -> Dict[str, float]:
        """
        Compute standard performance metrics for a trajectory.
        
        Args:
            trajectory: Trajectory to analyze
            
        Returns:
            Dictionary of performance metrics
        """
        total_reward = trajectory.total_reward
        mean_reward = jnp.mean(trajectory.rewards)
        
        # Compute additional metrics if trajectory has info
        metrics = {
            'total_reward': float(total_reward),
            'mean_reward': float(mean_reward),
            'reward_std': float(jnp.std(trajectory.rewards)),
            'trajectory_length': trajectory.length
        }
        
        # Add domain-specific metrics if available
        if trajectory.infos:
            if 'inventory' in trajectory.infos:
                final_inventory = trajectory.infos['inventory'][-1]
                metrics['final_inventory'] = float(final_inventory)
                metrics['inventory_variance'] = float(jnp.var(trajectory.infos['inventory']))
            
            if 'belief' in trajectory.infos:
                final_belief = trajectory.infos['belief'][-1]
                metrics['final_belief'] = float(final_belief)
                metrics['belief_change'] = float(jnp.abs(final_belief - trajectory.infos['belief'][0]))
        
        return metrics
    
    @staticmethod
    def analyze_batch_trajectories(batch_trajectories: BatchTrajectories) -> Dict[str, Any]:
        """
        Analyze batch of trajectories and compute aggregate statistics.
        
        Args:
            batch_trajectories: Batch of trajectories to analyze
            
        Returns:
            Dictionary of aggregate statistics
        """
        total_rewards = batch_trajectories.total_rewards
        
        analysis = {
            'batch_size': batch_trajectories.batch_size,
            'trajectory_length': batch_trajectories.length,
            
            # Reward statistics
            'mean_total_reward': float(jnp.mean(total_rewards)),
            'std_total_reward': float(jnp.std(total_rewards)),
            'min_total_reward': float(jnp.min(total_rewards)),
            'max_total_reward': float(jnp.max(total_rewards)),
            'median_total_reward': float(jnp.median(total_rewards)),
            
            # Reward distribution quantiles
            'reward_q25': float(jnp.percentile(total_rewards, 25)),
            'reward_q75': float(jnp.percentile(total_rewards, 75)),
        }
        
        # Add domain-specific batch analysis
        if batch_trajectories.infos:
            if 'inventory' in batch_trajectories.infos:
                final_inventories = batch_trajectories.infos['inventory'][:, -1]
                analysis.update({
                    'mean_final_inventory': float(jnp.mean(final_inventories)),
                    'std_final_inventory': float(jnp.std(final_inventories))
                })
            
            if 'true_regime' in batch_trajectories.infos:
                # Regime analysis
                true_regimes = batch_trajectories.infos['true_regime'][:, -1]
                regime_distribution = jnp.mean(true_regimes)
                analysis['regime_distribution'] = float(regime_distribution)
        
        return analysis
    
    @staticmethod
    def compare_policies(trajectory_batches: List[BatchTrajectories], 
                        policy_names: List[str]) -> Dict[str, Any]:
        """
        Compare performance across different policies.
        
        Args:
            trajectory_batches: List of trajectory batches from different policies
            policy_names: Names of the policies
            
        Returns:
            Comparison analysis
        """
        comparison = {
            'policies': policy_names,
            'policy_performance': {}
        }
        
        for i, (batch, name) in enumerate(zip(trajectory_batches, policy_names)):
            analysis = TrajectoryAnalyzer.analyze_batch_trajectories(batch)
            comparison['policy_performance'][name] = analysis
        
        # Add relative performance metrics
        mean_rewards = [comparison['policy_performance'][name]['mean_total_reward'] 
                       for name in policy_names]
        
        best_policy_idx = jnp.argmax(jnp.array(mean_rewards))
        comparison['best_policy'] = policy_names[best_policy_idx]
        comparison['performance_ranking'] = sorted(
            zip(policy_names, mean_rewards), 
            key=lambda x: x[1], 
            reverse=True
        )
        
        return comparison


# Utility functions for trajectory generation
def generate_trajectory_from_policy(policy: ControlPolicy,
                                  environment: ControlEnvironment,
                                  n_steps: int,
                                  key: random.PRNGKey,
                                  initial_state: Optional[State] = None) -> Trajectory:
    """
    Convenience function to generate single trajectory.
    
    Args:
        policy: Control policy
        environment: Control environment
        n_steps: Number of steps
        key: Random key
        initial_state: Optional initial state (environment default if None)
        
    Returns:
        Generated trajectory
    """
    generator = TrajectoryGenerator(policy, environment)
    
    if initial_state is None:
        key, reset_key = random.split(key)
        initial_state = environment.reset(reset_key)
    
    return generator.generate_trajectory(initial_state, n_steps, key)


def generate_batch_trajectories_from_policy(policy: ControlPolicy,
                                          environment: ControlEnvironment,
                                          batch_size: int,
                                          n_steps: int,
                                          key: random.PRNGKey) -> BatchTrajectories:
    """
    Convenience function to generate batch of trajectories.
    
    Args:
        policy: Control policy
        environment: Control environment  
        batch_size: Number of trajectories
        n_steps: Number of steps per trajectory
        key: Random key
        
    Returns:
        Batch of generated trajectories
    """
    generator = TrajectoryGenerator(policy, environment)
    return generator.generate_batch_trajectories(batch_size, n_steps, key)